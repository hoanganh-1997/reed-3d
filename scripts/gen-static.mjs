// Generates the static-data migration from config/game.json.
// Usage: node scripts/gen-static.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const cfg = JSON.parse(readFileSync(new URL('../config/game.json', import.meta.url), 'utf8'));
const q = (v) => (v === null || v === undefined ? 'null' : typeof v === 'number' || typeof v === 'boolean' ? String(v) : `'${String(v).replace(/'/g, "''")}'`);

const upsert = (table, rows, cols) => {
  const values = rows.map((r) => `  (${cols.map((c) => q(r[c])).join(', ')})`).join(',\n');
  const updates = cols.filter((c) => c !== 'id').map((c) => `${c} = excluded.${c}`).join(', ');
  return `insert into public.${table} (${cols.join(', ')}) values\n${values}\non conflict (id) do update set ${updates};\n`;
};

const tierCols = ['id', 'name', 'label', 'length_cm', 'depth_cm', 'height_cm', 'unlock_level', 'unlock_cost_coins', 'max_fish', 'sort_order', 'max_size_fingers'];
const speciesCols = ['id', 'common_name', 'scientific_name', 'adult_length_cm', 'min_tier', 'starter', 'body_color', 'fin_color', 'accent_color', 'model_url', 'model_forward', 'display_name', 'unlock_level', 'price_coins', 'kind', 'max_per_tank'];

const sql = `-- GENERATED by scripts/gen-static.mjs from config/game.json. Do not edit by hand.
-- Idempotent: safe to re-run. Rows removed from the config are NOT deleted here.

insert into public.game_settings (id, data) values (1, ${q(JSON.stringify(cfg.settings))}::jsonb)
on conflict (id) do update set data = excluded.data;

-- sort_order is unique; shift existing rows out of the way before upserting.
update public.tank_tiers set sort_order = sort_order + 100000 where id in (${cfg.tankTiers.map((t) => q(t.id)).join(', ')});
${upsert('tank_tiers', cfg.tankTiers, tierCols)}
${upsert('species', cfg.species, speciesCols)}`;

const ts = new Date().toISOString().replace(/\D/g, '').slice(0, 14);
const out = process.argv[2] ?? `supabase/migrations/${ts}_static_data.sql`;
writeFileSync(out, sql);
console.log(`wrote ${out}`);
